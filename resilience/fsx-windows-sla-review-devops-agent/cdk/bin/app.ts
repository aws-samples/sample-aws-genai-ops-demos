#!/usr/bin/env node
/**
 * FSx for Windows SLA review with AWS DevOps Agent: four stacks.
 *
 *   FsxSlaReviewAgentSpace-<agent-region>   the Agent Space (shared construct), deployed first;
 *                                           its outputs feed the others as --context
 *   FsxSlaReviewDirectory-<region>          VPC + one self-managed Active Directory domain
 *                                           controller (EC2) + the service-account secret
 *   FsxSlaReviewFileSystem-<region>         the file system, its alarms, the lifecycle canary
 *                                           and the alarm -> webhook trigger chain (main stack)
 *   FsxSlaReviewLab-<region>                the Lab: engine + API (shared LabEngine), CloudFront
 *                                           site with Basic Auth
 *
 * deploy-all deploys Directory, waits for the domain controller to report ready (an SSM
 * parameter written by its user data), then deploys FileSystem and Lab: FSx joins the domain
 * at creation and fails after 30 minutes if the domain is not there yet.
 */
import * as cdk from 'aws-cdk-lib';
import { getRegion } from '../../../../shared/utils/aws-utils';
import { AgentSpaceStack } from '../lib/agent-space-stack';
import { DirectoryStack } from '../lib/directory-stack';
import { FileSystemStack } from '../lib/file-system-stack';
import { LabStack } from '../lib/lab-stack';

const app = new cdk.App();
const region = getRegion();
const env: cdk.Environment = { region };

const projectName: string = app.node.tryGetContext('projectName') ?? 'fsx-sla-review';
const devOpsAgentRegion: string = app.node.tryGetContext('devOpsAgentRegion') || region;
// Outputs of the Agent Space stack, passed back by deploy-all (never the secret value).
const webhookUrl: string = app.node.tryGetContext('devOpsAgentWebhookUrl') ?? '';
const webhookSecretArn: string = app.node.tryGetContext('devOpsAgentWebhookSecretArn') ?? '';
const devOpsAgentSpaceId: string = app.node.tryGetContext('devOpsAgentSpaceId') ?? '';
// Basic Auth credentials of the Lab site, generated by deploy-all and printed at the end.
const labUser: string = app.node.tryGetContext('labUser') ?? 'presenter';
const labPassword: string = app.node.tryGetContext('labPassword') ?? '';

new AgentSpaceStack(app, `FsxSlaReviewAgentSpace-${devOpsAgentRegion}`, {
  env: { region: devOpsAgentRegion },
  projectName,
  description: 'FSx for Windows SLA review demo: AWS DevOps Agent Agent Space, roles, operator app, webhook',
});

const directory = new DirectoryStack(app, `FsxSlaReviewDirectory-${region}`, {
  env,
  projectName,
  description: 'FSx for Windows SLA review demo: VPC and self-managed Active Directory domain controller',
});

const fileSystem = new FileSystemStack(app, `FsxSlaReviewFileSystem-${region}`, {
  env,
  projectName,
  vpc: directory.vpc,
  directory: directory.directory,
  webhookUrl,
  webhookSecretArn,
  webhookSecretRegion: devOpsAgentRegion,
  description: 'FSx for Windows SLA review with AWS DevOps Agent (uksb-do9bhieqqh)(tag:fsx-windows-sla-review,resilience)',
});

new LabStack(app, `FsxSlaReviewLab-${region}`, {
  env,
  projectName,
  fileSystem: fileSystem.fileSystem,
  directory: directory.directory,
  alarms: fileSystem.alarms,
  triggerFunctionName: fileSystem.triggerFunctionName,
  devOpsAgentRegion,
  devOpsAgentSpaceId,
  labUser,
  labPassword,
  description: 'FSx for Windows SLA review demo: the Demo Lab (engine, API, site)',
});
