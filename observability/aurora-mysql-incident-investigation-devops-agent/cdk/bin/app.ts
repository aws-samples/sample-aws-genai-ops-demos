#!/usr/bin/env node
/**
 * Aurora MySQL incident investigation with business context (AWS DevOps Agent): three stacks.
 *
 *   AuroraBizCtxAgentSpace-<agent-region>   the Agent Space (shared construct), deployed first;
 *                                           its outputs feed the others as --context
 *   AuroraBizCtxDatabase-<region>           VPC, Aurora MySQL cluster with its business tags, the
 *                                           connection load function, the DatabaseConnections
 *                                           alarm and the alarm -> webhook trigger chain (main stack)
 *   AuroraBizCtxLab-<region>                the Lab: engine + API (shared LabEngine), CloudFront
 *                                           site with Basic Auth
 */
import * as cdk from 'aws-cdk-lib';
import { getRegion } from '../../../../shared/utils/aws-utils';
import { AgentSpaceStack } from '../lib/agent-space-stack';
import { DatabaseStack } from '../lib/database-stack';
import { LabStack } from '../lib/lab-stack';

const app = new cdk.App();
const region = getRegion();
const env: cdk.Environment = { region };

const projectName: string = app.node.tryGetContext('projectName') ?? 'aurora-bizctx';
const devOpsAgentRegion: string = app.node.tryGetContext('devOpsAgentRegion') || region;
// Outputs of the Agent Space stack, passed back by deploy-all (never the secret value).
const webhookUrl: string = app.node.tryGetContext('devOpsAgentWebhookUrl') ?? '';
const webhookSecretArn: string = app.node.tryGetContext('devOpsAgentWebhookSecretArn') ?? '';
const devOpsAgentSpaceId: string = app.node.tryGetContext('devOpsAgentSpaceId') ?? '';
// Basic Auth credentials of the Lab site, generated by deploy-all and printed at the end.
const labUser: string = app.node.tryGetContext('labUser') ?? 'presenter';
const labPassword: string = app.node.tryGetContext('labPassword') ?? '';

new AgentSpaceStack(app, `AuroraBizCtxAgentSpace-${devOpsAgentRegion}`, {
  env: { region: devOpsAgentRegion },
  projectName,
  description: 'Aurora MySQL incident investigation demo: AWS DevOps Agent Agent Space, roles, operator app, webhook',
});

const database = new DatabaseStack(app, `AuroraBizCtxDatabase-${region}`, {
  env,
  projectName,
  webhookUrl,
  webhookSecretArn,
  webhookSecretRegion: devOpsAgentRegion,
  description: 'Aurora MySQL incident investigation with business context, AWS DevOps Agent (uksb-do9bhieqqh)(tag:aurora-mysql-incident-investigation-devops-agent,observability)',
});

new LabStack(app, `AuroraBizCtxLab-${region}`, {
  env,
  projectName,
  database,
  devOpsAgentRegion,
  devOpsAgentSpaceId,
  labUser,
  labPassword,
  description: 'Aurora MySQL incident investigation demo: the Demo Lab (engine, API, site)',
});
